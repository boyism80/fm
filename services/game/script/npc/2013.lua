return {
	on_click = function(me, npc)
		local categories = {}
		for i, catalog in ipairs(catalogs) do
			categories[i] = catalog[1]
		end
		local cat = me:dialog_list(npc, "#e이벤트성 상점 #n입니다. 언제 사라질지 모르며, 무료 구매 가능한 품목은 항목에 의해 한정됩니다.", categories)
		if cat == nil then
			return
		end
		local goods = catalogs[cat][2]
		local choices = {}
		for i, row in ipairs(goods) do
			choices[i] = "#i" .. row[1] .. ":# #b#z" .. row[1] .. "##k (가격 : " .. row[2] .. ")"
		end
		local sel = me:dialog_list(npc, "	#e[ 소지중 메소 : " .. me:meso() .. " ]#n", choices)
		if sel == nil then
			return
		end
		local row = goods[sel]
		if row == nil then
			return
		end
		if not me:dialog_yes_no(npc, "#i" .. row[1] .. ":# #b#z" .. row[1] .. "##k을(를) " .. row[2] .. " meso로 구입하시겠습니까?") then
			return
		end
		local code = me:exchange({ meso = row[2] }, { item = { [row[1]] = 1 } })
		if code == ExchangeResult.LackCost then
			me:dialog(npc, "meso가 " .. row[2] .. "need")
			return
		end
		if code ~= ExchangeResult.OK then
			me:dialog(npc, "아이템창이 부족합니다.")
			return
		end
		me:dialog(npc, "#b#z" .. row[1] .. "##k을(를) " .. row[2] .. " mesobought")
	end
}
