local COLORLESS_HAIRS = { [30010] = true, [30100] = true }
local BLACK_EYE_FACES = { [20071] = true, [20072] = true, [20079] = true, [21066] = true, [21067] = true, [24076] = true }

return {
	on_click = function(me, npc)
		local gender = me:gender()
		local label = "여성"
		if gender == 0 then
			label = "남성"
		end

		local sel = me:dialog_list(npc, "#e현재 모험가님의 성별은 " .. label .. "입니다.#n", {
			"#r헤어변경 [1]#k",
			"#r헤어변경 [2]#k",
			"#r헤어변경 [3]#k",
			"#r헤어변경 [4]#k",
			"#r헤어변경 [5]#k",
			"#r헤어변경 [6]#k",
			"#b헤어염색#k",
			"#r얼굴성형 [1]#k",
			"#r얼굴성형 [2]#k",
			"#r얼굴성형 [3]#k",
			"#b렌즈착용#k",
			"#d피부관리#k",
		})
		if sel == nil then
			return
		end

		if sel <= 6 then
			local color = me:hair() % 10
			local styles = {}
			for _, id in ipairs(HAIRS[gender][sel]) do
				if COLORLESS_HAIRS[id] then
					table.insert(styles, id)
				else
					table.insert(styles, id + color)
				end
			end
			local pick = me:dialog_style(npc, "원하는 아바타를 선택해주세요. (총 개수 : " .. #styles .. ")", styles)
			if pick == nil then
				return
			end
			me:hair(styles[pick])
		elseif sel == 7 then
			local base = math.floor(me:hair() / 10) * 10
			local styles = { base }
			if base ~= 30010 then
				for i = 1, 7 do
					table.insert(styles, base + i)
				end
			end
			local pick = me:dialog_style(npc, "원하는 아바타를 선택해주세요.", styles)
			if pick == nil then
				return
			end
			me:hair(styles[pick])
		elseif sel <= 10 then
			local face = me:face()
			local offset = face % 1000 - face % 100
			local styles = {}
			for _, id in ipairs(FACES[gender][sel - 7]) do
				if BLACK_EYE_FACES[id] then
					table.insert(styles, id)
				else
					table.insert(styles, id + offset)
				end
			end
			local pick = me:dialog_style(npc, "원하는 아바타를 선택해주세요. (총 개수 : " .. #styles .. ")", styles)
			if pick == nil then
				return
			end
			me:face(styles[pick])
		elseif sel == 11 then
			local face = me:face()
			local base = face % 100 + face - face % 1000
			if BLACK_EYE_FACES[base] then
				me:dialog(npc, "현재 모험가님이 하고 계신 성형은 검은색 눈밖에 없습니다.")
				return
			end
			local styles = {}
			for i = 0, 7 do
				table.insert(styles, base + i * 100)
			end
			local pick = me:dialog_style(npc, "원하는 아바타를 선택해주세요.", styles)
			if pick == nil then
				return
			end
			me:face(styles[pick])
		else
			local pick = me:dialog_style(npc, "원하는 피부를 선택해주세요.", SKINS)
			if pick == nil then
				return
			end
			me:skin(SKINS[pick])
		end
	end,
}
