local function item_count(me, item_id)
	local count = 0
	for _, it in pairs(me:item(item_id)) do
		count = count + it:count()
	end
	return count
end

local function pick(spec)
	local roll = math.random(1, spec[1])
	for _, row in ipairs(spec[2]) do
		if row[1] == "==" and roll == row[2] then
			return row[3], row[4]
		end
		if row[1] == "<=" and roll <= row[2] then
			return row[3], row[4]
		end
		if row[1] == "else" then
			return row[3], row[4]
		end
	end
end

return {
	on_click = function(me, npc)
		if me:dialog(npc, "어이 자네, 시간 좀 있는가? 음. 난 이것저것을 수집하는게 취미라네. 내가 원하는 아이템을 가져오면 자네에게 필요할만한 물건으로 바꿔주지. 다만 내가 주는 물건은 만날때 마다 바뀔 수 있다네. 어떤가? 생각 있는가?", false, true) == false then
			me:dialog(npc, "흠. 그렇다면 어쩔 수 없군.", false, true)
			return
		end
		local options = {}
		for i, item_id in ipairs(materials) do
			options[i] = "#t" .. item_id .. "# 100개"
		end
		local sel = me:dialog_list(npc, "좋아! 먼저 자네가 교환하고자 하는 아이템을 선택하게. 더 좋은 전리품일수록 더 좋은 아이템을 얻을 수 있다네.", options)
		if sel == nil then
			return
		end
		local material = materials[sel]
		if material == nil then
			return
		end
		local ask = "어디보자, 정말 #b#t" .. material .. "# 100개#k를 교환하고 싶어? 교환하기 전에 인벤토리 공간이 충분히 있는지 확인하라구. 그래서 정말 교환하고싶나?"
		if me:dialog_yes_no(npc, ask) == false then
			me:dialog(npc, "흠. 그렇다면 어쩔 수 없군.", false, true)
			return
		end
		if item_count(me, material) < 100 then
			me:dialog(npc, "자네..아이템은 분명 제대로 갖고 있는건가?")
			return
		end
		if me:empty_slots(InventoryType.Use) < 1 or me:empty_slots(InventoryType.Etc) < 1 then
			me:dialog(npc, "자네.. 인벤토리 공간이 부족하지는 않나?", false, true)
			return
		end
		local reward_id, reward_count = pick(rewards[material])
		local code = me:exchange({ item = { [material] = 100 } }, { item = { [reward_id] = reward_count }, exp = 500, random = true })
		if code == ExchangeResult.LackCost then
			me:dialog(npc, "자네..아이템은 분명 제대로 갖고 있는건가?")
			return
		end
		if code ~= ExchangeResult.OK then
			me:dialog(npc, "자네.. 인벤토리 공간이 부족하지는 않나?", false, true)
			return
		end
		me:dialog(npc, "자, 교환이 다 되었다네. 어떤가? 마음에 드는가? 다음번에 올땐 더 좋은 아이템이 있을 수 있으니 기대하게나.")
	end
}
