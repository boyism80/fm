return {
	on_click = function(me, npc)
		local sel = me:dialog_list(npc, "공장 여기까지 어쩐 일인가..? 필요한 것이라도 있나? \r\n#b", {
			" 촉진제가 뭐죠?",
			" 제조법이 뭐죠?",
			" 촉진제로 한손 무기 제작",
			" 촉진제로 두손 무기 제작",
			" 한손 무기 제작",
			" 두손 무기 제작",
		})
		if sel == nil then
			return
		end
		if sel == 1 then
			me:dialog(npc, "촉진제는 여러 아이템을 만들때 첨가할 수 있는 특수한 약이지. 몬스터에게서 구하실 수 있을거야. 어쨌든, 촉진제는 아이템을 만들때 일정 확률로 옵션이 더 좋아질 수 있게 되지. 하지만 10%의 확률로 제작에 실패할 수도 있으니 신중하게 결정해야하지.")
			return
		end
		if sel == 2 then
			me:dialog(npc, "아이템 제조법은 무기를 제작할때 필요한 제조법이라네. 아마 몬스터들에게서 구할 수 있을걸세.")
			return
		end

		local stimulator = sel == 3 or sel == 4
		local weapons = ONE_HANDED
		if sel == 4 or sel == 6 then
			weapons = TWO_HANDED
		end
		local type_options = {}
		for i, weapon in ipairs(weapons) do
			type_options[i] = weapon.name
		end
		local type_sel = me:dialog_list(npc, "그래? 어떤 무기를 만들고 싶은가?\r\n#b", type_options)
		if type_sel == nil then
			return
		end

		local weapon = weapons[type_sel]
		local recipes = weapon.items
		if stimulator and weapon.stimulator_items ~= nil then
			recipes = weapon.stimulator_items
		end
		local item_options = {}
		for i, recipe in ipairs(recipes) do
			item_options[i] = " #i" .. recipe.item .. "# #z" .. recipe.item .. "##k"
		end
		local item_sel = me:dialog_list(npc, "어떤 무기를 제작하고 싶나?\r\n#b", item_options)
		if item_sel == nil then
			return
		end

		local recipe = recipes[item_sel]
		local mats = recipe.mats
		if stimulator and weapon.stimulator ~= nil then
			mats = { recipe.mats[1], { weapon.stimulator, 1 } }
			for i = 2, #recipe.mats do
				mats[#mats + 1] = recipe.mats[i]
			end
		end
		local text = "만들고 싶은 아이템이 #b#t" .. recipe.item .. "##k 인가? 재료는 아래와 같다네.\r\n"
		for _, mat in ipairs(mats) do
			text = text .. "#b#v" .. mat[1] .. "# #t" .. mat[1] .. "# " .. mat[2] .. "개#k\r\n"
		end
		text = text .. "#b#i4031138# " .. recipe.cost .. " 메소#k\r\n"
		text = text .. "\r\n이 아이템을 정말 만들어 보겠나?"
		if not me:dialog_yes_no(npc, text) then
			me:dialog(npc, "그런가? 아직 재료가 부족한 모양이지? 준비가 되면 언제든지 나를 찾아오게나.")
			return
		end

		if me:meso() < recipe.cost then
			me:dialog(npc, "제작 수수료는 올바르게 갖고 있는건가? 다시 한번 확인해 주겠나?")
			return
		end
		local cost_items = {}
		for _, mat in ipairs(mats) do
			cost_items[mat[1]] = mat[2]
		end

		if stimulator then
			local code = me:exchange({ item = cost_items, meso = recipe.cost }, { item = { [recipe.item] = 1 }, random = true })
			if code == ExchangeResult.LackCapacity then
				me:dialog(npc, "인벤토리 공간이 부족한거 아닌가..? 제대로 다시 한번 확인해 보게.")
				return
			end
			if code ~= ExchangeResult.OK then
				me:dialog(npc, "흐음. 재료중에 부족한 재료가 있는 것 같군. 다시 한번 확인해 주겠나?")
				return
			end
			me:dialog(npc, "자, 다 되었다네. 어떤가? 멋진 물건이지? 다음에도 필요하면 언제든지 나를 찾아오게나!")
			return
		end
		local code = me:exchange({ item = cost_items, meso = recipe.cost }, { item = { [recipe.item] = 1 } })
		if code == ExchangeResult.LackCapacity then
			me:dialog(npc, "인벤토리 공간이 부족한거 아닌가..? 제대로 다시 한번 확인해 보게.")
			return
		end
		if code ~= ExchangeResult.OK then
			me:dialog(npc, "흐음. 재료중에 부족한 재료가 있는 것 같군. 다시 한번 확인해 주겠나?")
			return
		end
		me:dialog(npc, "자, 다 되었다네. 어떤가? 멋진 물건이지? 다음에도 필요하면 언제든지 나를 찾아오게나!")
	end
}
