local DEFAULT = { id = 2000003, n = 100 }

local function bump_clear_count(me)
	local q = me:quest(REPEAT_QUEST)
	if q == nil then
		return
	end
	if not q:started() then
		q:start("1")
		return
	end
	local count = tonumber(q:record()) or 0
	q:record(tostring(count + 1))
end

return {
	on_click = function(me, npc)
		me:dialog(npc, "모든 스테이지를 클리어 하고 이곳까지 오시다니 대단하시군요. 클리어를 축하드리며 작은 선물을 준비했습니다. 선물을 받으시기 전에 미리 아이템 소비창이나 기타창에 빈 칸이 하나 이상 있는지 확인해 주세요~")
		local rnum = math.random(0, 250)
		local reward = rewards[rnum] or DEFAULT
		local item = pq.gain_item(me, reward.id, reward.n)
		if item == nil then
			me:dialog(npc, "장비, 소비, 설치, 기타 탭을 최소 2칸 이상 비우신 후 다시 말을 걸어주세요.")
			return
		end
		bump_clear_count(me)
		me:map(LOBBY_MAP)
	end
}
