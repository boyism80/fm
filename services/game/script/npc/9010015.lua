	on_click = function(me, npc)
		local choices = {}
		for i, spot in ipairs(spots) do
			choices[i] = spot[2]
		end
		local sel = me:dialog_list(npc, "사냥이동 기능 오픈!", choices)
		if sel == nil then
			return
		end
		local spot = spots[sel]
		if spot == nil or id2map(spot[1]) == nil then
			me:dialog(npc, "아직 갈 수 없는 곳입니다.")
			return
		end
		me:map(spot[1])
	end
}
